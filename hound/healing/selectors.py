"""Self-healing selector store.

Every scraper eventually breaks because someone renamed a CSS class. The usual
response is an alert, a night of lost sleep, and a hotfix.

Hound treats a broken selector as a learning opportunity: when an action fails,
it looks for a replacement by scoring candidate selectors on the live DOM, and
only adopts one once it has been *verified* against the page - not merely
found. The fix is written back, keyed to the site, so the next run starts
already repaired.

The verification step is what separates this from "guess a selector and hope".
Adopting an unverified replacement is how scrapers silently start returning the
wrong data, which is worse than failing loudly.
"""

from __future__ import annotations

import json
import re
import sqlite3
import time
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Callable, Iterable

# Generated by the recovery candidates below; matches Playwright-ish semantics
# well enough for the heuristic scoring to work.
_CSS_HASH = re.compile(r"#[A-Za-z_][\w-]*")
_CSS_CLASS = re.compile(r"\.([A-Za-z_][\w-]*)")
_ATTR = re.compile(r"\[([\w-]+)\s*[~^$*|]?=\s*[\"']([^\"']+)[\"']\]")
_TEXT_LITERAL = re.compile(r"text=[\"']([^\"']+)[\"']")
_TEXT_BARE = re.compile(r"text=([^\s\[\]>\(\)]+)")
_TEST_ID = re.compile(r"data-testid=[\"']([^\"']+)[\"']")
_NAME = re.compile(r"name=[\"']([^\"']+)[\"']")

_STABLE_HINTS = (
    "testid",
    "test-id",
    "data-qa",
    "data-cy",
    "aria-label",
    "role",
    "name",
    "id",
    "title",
    "placeholder",
    "alt",
    "href",
)

_VOLATILE_HINTS = (
    "css-",
    "sc-",
    "jsx-",
    "emotion",
    "styled",
    "random",
    "uuid",
    "hash",
    "generated",
    "btn-",
    "col-",
    "row-",
)


@dataclass
class SelectorCandidate:
    selector: str
    score: float
    reason: str

    def to_dict(self) -> dict:
        return {"selector": self.selector, "score": round(self.score, 3), "reason": self.reason}


@dataclass
class HealingOutcome:
    """What the healer decided, and why - always explained, never silent."""

    healed: bool
    original: str
    selector: str
    confidence: float
    verified: bool
    detail: str = ""
    candidates: list[SelectorCandidate] = field(default_factory=list)

    def to_dict(self) -> dict:
        return {
            "healed": self.healed,
            "original": self.original,
            "selector": self.selector,
            "confidence": round(self.confidence, 3),
            "verified": self.verified,
            "detail": self.detail,
            "candidates": [c.to_dict() for c in self.candidates[:5]],
        }


class SelectorStore:
    """Persisted, per-site selector overrides backed by SQLite."""

    def __init__(self, path: str | Path = ":memory:"):
        self.path = str(path)
        self._conn = sqlite3.connect(self.path)
        self._conn.row_factory = sqlite3.Row
        self._init_schema()

    def _init_schema(self) -> None:
        self._conn.executescript(
            """
            CREATE TABLE IF NOT EXISTS selector_overrides (
                site        TEXT NOT NULL,
                logical_key TEXT NOT NULL,
                selector    TEXT NOT NULL,
                original    TEXT NOT NULL,
                confidence  REAL NOT NULL DEFAULT 0,
                verified    INTEGER NOT NULL DEFAULT 0,
                hits        INTEGER NOT NULL DEFAULT 0,
                misses      INTEGER NOT NULL DEFAULT 0,
                updated_at  REAL NOT NULL,
                PRIMARY KEY (site, logical_key)
            );
            CREATE TABLE IF NOT EXISTS healing_log (
                id          INTEGER PRIMARY KEY AUTOINCREMENT,
                site        TEXT NOT NULL,
                logical_key TEXT NOT NULL,
                original    TEXT NOT NULL,
                replacement TEXT,
                verified    INTEGER NOT NULL,
                confidence  REAL NOT NULL,
                created_at  REAL NOT NULL
            );
            """
        )
        self._conn.commit()

    # -- read / write ----------------------------------------------------

    def get(self, site: str, logical_key: str) -> str | None:
        row = self._conn.execute(
            "SELECT selector FROM selector_overrides WHERE site = ? AND logical_key = ?",
            (site, logical_key),
        ).fetchone()
        return row["selector"] if row else None

    def record_heal(self, outcome: HealingOutcome, site: str, logical_key: str) -> None:
        now = time.time()
        self._conn.execute(
            """
            INSERT INTO selector_overrides
                (site, logical_key, selector, original, confidence, verified, hits, misses, updated_at)
            VALUES (?, ?, ?, ?, ?, ?, 1, 0, ?)
            ON CONFLICT(site, logical_key) DO UPDATE SET
                selector = excluded.selector,
                original = excluded.original,
                confidence = excluded.confidence,
                verified = excluded.verified,
                hits = selector_overrides.hits + 1,
                updated_at = excluded.updated_at
            """,
            (
                site,
                logical_key,
                outcome.selector,
                outcome.original,
                outcome.confidence,
                int(outcome.verified),
                now,
            ),
        )
        self._conn.execute(
            """
            INSERT INTO healing_log
                (site, logical_key, original, replacement, verified, confidence, created_at)
            VALUES (?, ?, ?, ?, ?, ?, ?)
            """,
            (
                site,
                logical_key,
                outcome.original,
                outcome.selector,
                int(outcome.verified),
                outcome.confidence,
                now,
            ),
        )
        self._conn.commit()

    def record_miss(self, site: str, logical_key: str) -> None:
        """A known override stopped working, so the site changed again."""
        self._conn.execute(
            """
            UPDATE selector_overrides
               SET misses = misses + 1, verified = 0, updated_at = ?
             WHERE site = ? AND logical_key = ?
            """,
            (time.time(), site, logical_key),
        )
        self._conn.commit()

    def history(self, site: str, limit: int = 20) -> list[dict]:
        rows = self._conn.execute(
            """
            SELECT logical_key, original, replacement, verified, confidence, created_at
              FROM healing_log WHERE site = ? ORDER BY id DESC LIMIT ?
            """,
            (site, limit),
        ).fetchall()
        return [dict(row) for row in rows]

    def stats(self) -> dict:
        total = self._conn.execute("SELECT COUNT(*) c FROM selector_overrides").fetchone()["c"]
        verified = self._conn.execute(
            "SELECT COUNT(*) c FROM selector_overrides WHERE verified = 1"
        ).fetchone()["c"]
        return {"overrides": total, "verified": verified, "unverified": total - verified}

    def close(self) -> None:
        self._conn.close()


# -- candidate generation and scoring ---------------------------------------


def _volatility(selector: str) -> float:
    """How likely this selector is to change on the next deploy."""
    low = selector.lower()
    hits = sum(1 for hint in _VOLATILE_HINTS if hint in low)
    return min(hits * 0.3, 0.9)


def score_candidate(selector: str, *, matches: int, expected: int = 1) -> float:
    """Score a candidate selector from 0 to 1.

    A selector that matches exactly the expected number of elements scores far
    higher than one that matches everything on the page, because "the first
    ``div``" is technically a selector and practically a bug.
    """
    if matches == 0:
        return 0.0

    length_penalty = min(len(selector) / 200.0, 0.3)
    stability = 1.0 - _volatility(selector)

    if expected <= 1:
        precision = 1.0 if matches == 1 else max(0.0, 1.0 - (matches - 1) * 0.15)
    else:
        delta = abs(matches - expected)
        precision = max(0.0, 1.0 - delta / max(expected, 1))

    specificity_bonus = 0.1 if any(
        hint in selector.lower() for hint in ("testid", "data-qa", "aria-label", "role")
    ) else 0.0

    raw = 0.45 * precision + 0.35 * stability + 0.20 * (1 - length_penalty) + specificity_bonus
    return round(min(raw, 1.0), 4)


def generate_candidates(selector: str) -> list[str]:
    """Propose replacements for a broken selector.

    Ordered from most durable to most fragile, because the caller scores them
    and only falls back to fragile ones when nothing better exists.
    """
    out: list[str] = []

    def add(value: str) -> None:
        if value and value != selector and value not in out:
            out.append(value)

    for match in _TEST_ID.findall(selector):
        add(f'[data-testid="{match}"]')
    for match in _ATTR.findall(selector):
        name, value = match
        if name.startswith("data-") or name in {"aria-label", "role", "name", "title", "placeholder"}:
            add(f'[{name}="{value}"]')
    for match in _TEXT_LITERAL.findall(selector):
        add(f'[aria-label="{match}"]')
        add(f'text="{match}"')
    for match in _TEXT_BARE.findall(selector):
        # Playwright accepts unquoted text= selectors. They are common in
        # hand-written scrapers and were previously unparseable here.
        add(f'[aria-label="{match}"]')
        add(f'text="{match}"')

    tag = _target_tag(selector)

    for match in _CSS_HASH.findall(selector):
        add(match)
    classes = _CSS_CLASS.findall(selector)
    for cls in classes:
        add(f"{tag}.{cls}")
    for name in _NAME.findall(selector):
        add(f'{tag}[name="{name}"]')

    if classes:
        add(f"{tag}.{classes[-1]}")
    if len(classes) >= 2:
        add(".".join([tag, classes[0], classes[-1]]))

    add(tag)
    return out


def _target_tag(selector: str) -> str:
    """The tag name of the element the selector actually targets.

    For a descendant chain the target is the *last* segment, so
    ``div.wrapper > button.go`` targets a ``button``. Getting this wrong
    produces selectors like ``divspanbutton.go`` that match nothing, which is
    exactly the kind of silently-useless candidate that makes a scraper look
    broken rather than merely mis-targeted.
    """
    parts = re.split(r"\s*[>+~]\s*", selector.strip())
    last = parts[-1] if parts else selector
    match = re.match(r"^[A-Za-z][\w-]*", last)
    return match.group(0).lower() if match else "div"


def heal(
    original: str,
    *,
    probe: Callable[[str], int],
    verify: Callable[[str], bool] | None = None,
    expected_matches: int = 1,
    min_confidence: float = 0.55,
    max_attempts: int = 8,
) -> HealingOutcome:
    """Try to repair a broken selector against the live page.

    ``probe`` returns how many elements a candidate selector matches.
    ``verify`` optionally confirms the candidate yields the right *data*, not
    just that it matches something. Without ``verify`` a selector is adopted on
    match count alone, which is recorded as ``verified=False`` so the caller
    knows the difference.
    """
    candidates = generate_candidates(original)[:max_attempts]
    scored: list[SelectorCandidate] = []

    for candidate in candidates:
        try:
            matches = probe(candidate)
        except Exception:
            continue
        if matches <= 0:
            continue
        score = score_candidate(candidate, matches=matches, expected=expected_matches)
        reason = f"matches={matches}"
        if _volatility(candidate) > 0:
            reason += ", volatile"
        scored.append(SelectorCandidate(candidate, score, reason))

    if not scored:
        return HealingOutcome(
            healed=False,
            original=original,
            selector=original,
            confidence=0.0,
            verified=False,
            detail="no candidate selector matched anything on the page",
        )

    scored.sort(key=lambda c: c.score, reverse=True)
    best = scored[0]

    if best.score < min_confidence:
        return HealingOutcome(
            healed=False,
            original=original,
            selector=original,
            confidence=best.score,
            verified=False,
            detail=(
                f"best candidate {best.selector!r} scored {best.score:.2f}, "
                f"below the {min_confidence} adoption threshold"
            ),
            candidates=scored,
        )

    verified = False
    if verify is not None:
        try:
            verified = bool(verify(best.selector))
        except Exception:
            verified = False

    return HealingOutcome(
        healed=True,
        original=original,
        selector=best.selector,
        confidence=best.score,
        verified=verified,
        detail=(
            f"replaced with {best.selector!r} ({best.reason}); "
            + ("verified against expected data" if verified else "matched, but data not verified")
        ),
        candidates=scored,
    )


async def heal_async(
    original: str,
    *,
    probe: Callable[[str], Any],
    verify: Callable[[str], Any] | None = None,
    expected_matches: int = 1,
    min_confidence: float = 0.55,
    max_attempts: int = 8,
) -> HealingOutcome:
    """Async twin of :func:`heal` for live browsers.

    Identical scoring; the difference is that ``probe``/``verify`` are coroutine
    functions because a Playwright selector query is inherently a round trip.
    Kept separate rather than overloading ``heal`` so the synchronous version
    stays trivially unit-testable with plain callables.
    """
    candidates = generate_candidates(original)[:max_attempts]
    scored: list[SelectorCandidate] = []

    for candidate in candidates:
        try:
            matches = await probe(candidate)
        except Exception:
            continue
        if not matches or matches <= 0:
            continue
        score = score_candidate(candidate, matches=int(matches), expected=expected_matches)
        reason = f"matches={int(matches)}"
        if _volatility(candidate) > 0:
            reason += ", volatile"
        scored.append(SelectorCandidate(candidate, score, reason))

    if not scored:
        return HealingOutcome(
            healed=False,
            original=original,
            selector=original,
            confidence=0.0,
            verified=False,
            detail="no candidate selector matched anything on the page",
        )

    scored.sort(key=lambda c: c.score, reverse=True)
    best = scored[0]

    if best.score < min_confidence:
        return HealingOutcome(
            healed=False,
            original=original,
            selector=original,
            confidence=best.score,
            verified=False,
            detail=(
                f"best candidate {best.selector!r} scored {best.score:.2f}, "
                f"below the {min_confidence} adoption threshold"
            ),
            candidates=scored,
        )

    verified = False
    if verify is not None:
        try:
            verified = bool(await verify(best.selector))
        except Exception:
            verified = False

    return HealingOutcome(
        healed=True,
        original=original,
        selector=best.selector,
        confidence=best.score,
        verified=verified,
        detail=(
            f"replaced with {best.selector!r} ({best.reason}); "
            + ("verified against expected data" if verified else "matched, but data not verified")
        ),
        candidates=scored,
    )
